(() => {
  const param = new URLSearchParams(location.search).get('lang');
  let saved = 'vi';
  try { saved = localStorage.getItem('yeswood-language') || 'vi'; } catch {}
  const language = param === 'en' || param === 'vi' ? param : saved;
  try { localStorage.setItem('yeswood-language', language); } catch {}
  document.documentElement.lang = language;

  const switcher = document.querySelector('.language-switch');
  const options = document.querySelector('#language-options');
  if (switcher && options) {
    switcher.setAttribute('aria-label', language === 'en' ? 'Choose language' : 'Chọn ngôn ngữ');
    switcher.title = language === 'en' ? 'Choose language' : 'Chọn ngôn ngữ';
    const close = () => { options.hidden = true; switcher.setAttribute('aria-expanded','false'); };
    switcher.addEventListener('click', () => {
      const opening = options.hidden;
      options.hidden = !opening;
      switcher.setAttribute('aria-expanded',String(opening));
      if (opening) options.querySelector(`[data-language="${language}"]`).focus();
    });
    options.querySelectorAll('[data-language]').forEach(option => {
      option.setAttribute('aria-pressed',String(option.dataset.language === language));
      option.addEventListener('click', () => {
        const choice = option.dataset.language;
        close();
        if (choice === language) { switcher.focus(); return; }
        try { localStorage.setItem('yeswood-language', choice); } catch {}
        const url = new URL(location.href);
        if (choice === 'en') url.searchParams.set('lang', 'en');
        else url.searchParams.delete('lang');
        location.assign(url.href);
      });
    });
    document.addEventListener('click', event => {
      if (!event.target.closest('.language-menu')) close();
    });
    document.addEventListener('keydown', event => {
      if (event.key === 'Escape' && !options.hidden) { close(); switcher.focus(); }
    });
  }
  if (language !== 'en') return;

  const translate = source => {
    if (Object.hasOwn(YESWOOD_EN, source)) return YESWOOD_EN[source];
    let match = source.match(/^(\d+) sản phẩm(?: đã lưu)?$/);
    if (match) return `${match[1]} ${source.endsWith('đã lưu') ? 'saved ' : ''}products`;
    match = source.match(/^Vân gỗ tự nhiên (\d+)$/);
    if (match) return `Natural wood grain ${match[1]}`;
    match = source.match(/^Minh họa cột mốc (\d{4})$/);
    if (match) return `Illustration of the ${match[1]} milestone`;
    match = source.match(/^Xem ảnh sản phẩm (\d+)$/);
    if (match) return `View product image ${match[1]}`;
    match = source.match(/^Cảm hứng (phòng .+)$/i);
    if (match) return `${YESWOOD_EN[match[1][0].toUpperCase()+match[1].slice(1)] || 'Room'} Inspiration`;
    match = source.match(/^Danh mục nội thất (phòng .+)$/i);
    if (match) return `${YESWOOD_EN[match[1][0].toUpperCase()+match[1].slice(1)] || 'Room'} Furniture Categories`;
    match = source.match(/^Danh sách (.+)$/);
    if (match) return `${translate(match[1][0].toUpperCase()+match[1].slice(1))} Listing`;
    match = source.match(/^Bỏ lưu (.+)$/);
    if (match) return `Remove ${translate(match[1])} from saved products`;
    match = source.match(/^(.+) \| YESWOOD$/);
    if (match) return `${translate(match[1])} | YESWOOD`;
    return source;
  };
  const translateValue = value => {
    const parts = value.match(/^(\s*)([\s\S]*?)(\s*)$/);
    if (!parts || !parts[2]) return value;
    return parts[1] + translate(parts[2]) + parts[3];
  };
  const attributes = ['alt','aria-label','placeholder','title','data-mail-subject'];
  function translateElement(element) {
    if (element.matches('.language-switch')) return;
    for (const attr of attributes) if (element.hasAttribute(attr)) {
      const before = element.getAttribute(attr), after = translateValue(before);
      if (before !== after) element.setAttribute(attr, after);
    }
    if (element.matches('input[name],select[name],textarea[name]')) {
      const before = element.getAttribute('name'), after = translateValue(before);
      if (before !== after) element.setAttribute('name', after);
    }
    if (element.matches('input[type=radio][value]')) {
      const before = element.value, after = translateValue(before);
      if (before !== after) element.value = after;
    }
  }
  function translateTree(root) {
    if (root.nodeType === Node.TEXT_NODE) {
      if (root.parentElement?.closest('script,style,.language-switch')) return;
      const after = translateValue(root.nodeValue);
      if (root.nodeValue !== after) root.nodeValue = after;
      return;
    }
    if (root.nodeType !== Node.ELEMENT_NODE) return;
    if (root.matches('script,style')) return;
    translateElement(root);
    const walk = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
    while (walk.nextNode()) {
      const node = walk.currentNode;
      if (node.nodeType === Node.ELEMENT_NODE) {
        if (!node.closest('script,style')) translateElement(node);
      } else if (!node.parentElement.closest('script,style,.language-switch')) {
        const after = translateValue(node.nodeValue);
        if (node.nodeValue !== after) node.nodeValue = after;
      }
    }
  }
  translateTree(document.documentElement);
  new MutationObserver(records => {
    for (const record of records) {
      if (record.type === 'characterData') translateTree(record.target);
      else for (const node of record.addedNodes) translateTree(node);
    }
  }).observe(document.documentElement,{subtree:true,childList:true,characterData:true});
})();
